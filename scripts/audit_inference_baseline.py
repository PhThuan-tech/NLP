"""Inspect immutable trained archives without loading weights or changing data."""
from __future__ import annotations
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import re
import zipfile


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def labels(source, prediction):
    out = []
    if not prediction.strip(): out.append("E1")
    structural = [r"(?m)^\s*#{1,6} ", r"(?m)^\s*(?:\d+[.)]|[a-z][)]|[-+*]) ", r"(?m)^\s*\|.*\|\s*$"]
    if any(len(re.findall(p, source)) > len(re.findall(p, prediction)) for p in structural): out.append("E2")
    if re.search(r"(?:/ND|of the|\band|People[’'])\s*$", prediction, re.I): out.append("E3")
    if re.search(r"\b(\w+(?:\s+\w+){1,3})\s+\1\s+\1\b", prediction, re.I): out.append("E4")
    if any(len(re.findall(p, source)) != len(re.findall(p, prediction)) for p in structural): out.append("E5")
    # Temporary M0 heuristic; canonical S5 taxonomy is generated by the evaluation CLI.
    ids = lambda t: Counter(re.sub(r"\s", "", m).upper().replace("Đ", "D") for m in re.findall(r"\d+/\d{4}/[A-Za-zĐđ]+(?:-[A-Za-zĐđ0-9]+)*", t))
    if ids(source) != ids(prediction): out.append("E6")
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path("."))
    parser.add_argument("--output", type=Path, default=Path("reports/inference_pipeline"))
    args = parser.parse_args()
    import sacrebleu
    dev_file = args.root / "artifacts/processed_clean_semantic_seed67_v3/segments_dev_vi2en.jsonl"
    dev = [json.loads(line) for line in dev_file.read_text(encoding="utf-8").splitlines()]
    candidates = sorted((args.root / "modelAI").glob("*vi2en*zip"))
    if len(candidates) != 1: raise ValueError("Select exactly one VI2EN archive; do not mix runs")
    archive = candidates[0]
    with zipfile.ZipFile(archive) as z:
        raw = z.read("predictions/validation_predictions.jsonl")
        saved = [json.loads(line) for line in raw.decode().splitlines()]
        config = json.loads(z.read("resolved_config.json"))
        adapter_hash = sha256(z.read("best_model/adapter_model.safetensors"))
    predictions = {r["segment_id"]: r for r in saved}
    if set(predictions) != {r["segment_id"] for r in dev}: raise ValueError("Dev snapshot IDs do not match")
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "baseline_predictions.jsonl").write_bytes(raw)
    texts = [predictions[r["segment_id"]]["prediction"] for r in dev]
    targets = [r["target"] for r in dev]
    bleu = sacrebleu.metrics.BLEU(); chrf = sacrebleu.metrics.CHRF(word_order=2)
    counts = Counter(); examples = {f"E{i}": [] for i in range(1, 8)}
    for r, text in zip(dev, texts):
        for label in labels(r["source"], text):
            counts[label] += 1
            if len(examples[label]) < 20: examples[label].append({"id":r["segment_id"], "source":r["source"], "prediction":text})
    summary = {"status":"snapshot_only", "records":len(dev), "dev_sha256":sha256(dev_file.read_bytes()), "archive":archive.name, "adapter_sha256":adapter_hash, "generation":config["generation"], "BLEU":bleu.corpus_score(texts,[targets]).score, "chrF++":chrf.corpus_score(texts,[targets]).score, "signatures":{"BLEU":str(bleu.get_signature()),"chrF++":str(chrf.get_signature())}, "sacrebleu_version":sacrebleu.__version__, "taxonomy":dict(counts), "examples":examples, "cause_probe_status":"pending_real_generation", "E7_status":"not_measured_no_approved_glossary", "taxonomy_note":"M0 temporary heuristic; not semantic error ground truth"}
    (args.output / "baseline_summary.json").write_text(json.dumps(summary,ensure_ascii=False,indent=2),encoding="utf-8")
    lines = ["# Baseline error taxonomy", "", "Status: saved full-dev snapshot; current service R0 rerun and EOS cause probe pending.", "", f"Records: {len(dev)}; BLEU: {summary['BLEU']:.6f}; chrF++: {summary['chrF++']:.6f}.", f"Dev SHA256: `{summary['dev_sha256']}`", f"Adapter SHA256: `{adapter_hash}`", "", "| Label | Heuristic count | Rate |", "|---|---:|---:|"]
    lines += [f"| E{i} | {counts[f'E{i}']} | {100*counts[f'E{i}']/len(dev):.3f}% |" for i in range(1,8)]
    lines += ["", "E7 is unmeasured (no approved glossary), not zero confirmed errors.", "E2 counts missing structural markers, not confirmed missing meaning. E6 checks identifiers only at M0.", "EOS/cap cannot be inferred from saved text. No conclusion that ngram3 causes truncation.", "", "## Metric signatures", f"- BLEU: `{summary['signatures']['BLEU']}`", f"- chrF++: `{summary['signatures']['chrF++']}`"]
    for label, samples in examples.items():
        lines += ["", f"## {label}: {len(samples)} available examples (up to 20)"]
        for item in samples: lines += ["", f"### {item['id']}", "", "Source:", "```text", item["source"], "```", "Prediction:", "```text", item["prediction"], "```"]
    (args.output / "baseline_error_taxonomy.md").write_text("\n".join(lines)+"\n",encoding="utf-8")
    print(json.dumps({k:v for k,v in summary.items() if k not in {"examples"}},ensure_ascii=True,indent=2))


if __name__ == "__main__": main()
